"""사이트의 [수정 요청]과 GitHub 이슈를 서로 맞춘다.

사이트에서 올린 요청은 Firestore 의 users/{uid}/feedback/{id} 에 쌓인다. 상태(status)는
  new → (이슈를 만들면) issued → (이슈가 닫히면) done
1) new: 이슈를 만든다.
2) 사이트에서 내용을 고치면 edited=true 가 된다 → 고친 내용을 이슈 댓글로 단다(닫힌 이슈면 다시 연다).
3) issued 인데 이슈가 닫혔으면 → 마지막 답변(Claude 가 남긴 댓글)을 reply 로 옮기고 done 으로.
사이트의 연필 버튼 목록에서 상태·답변이 보인다.

필요한 GitHub Secrets / 환경변수
  FIREBASE_SERVICE_ACCOUNT  Firebase 콘솔 → 프로젝트 설정 → 서비스 계정 → 새 비공개 키 (JSON 전체)
  GITHUB_TOKEN              Actions 가 자동으로 넣어 준다 (issues: write)
  GITHUB_REPOSITORY         Actions 가 자동으로 넣어 준다 (owner/repo)
  FEEDBACK_UIDS             (선택) 이슈로 옮길 사용자 uid, 쉼표로 구분. 없으면 아래 OWNER_UIDS

다른 사람이 계정을 만들어 요청을 넣더라도 이슈가 되지 않도록 주인 계정 것만 옮긴다.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request

FIRESTORE = "https://firestore.googleapis.com/v1"
OWNER_UIDS = {"CBSAJUBKPXQPF3veVyMvHIDrBQT2"}   # sol 계정


def uid_of(name: str) -> str:
    """.../documents/users/{uid}/feedback/{id} 에서 uid."""
    parts = name.split("/")
    return parts[parts.index("users") + 1] if "users" in parts else ""


def http(method: str, url: str, token: str, body: dict | None = None) -> dict | list:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers={
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
        "Accept": "application/vnd.github+json" if "api.github.com" in url else "application/json",
        "User-Agent": "solworks-feedback",
    })
    with urllib.request.urlopen(req, timeout=30) as res:
        return json.loads(res.read() or b"null")


def plain(fields: dict) -> dict:
    """Firestore REST 형식({"text": {"stringValue": ...}})을 보통 dict 로."""
    out = {}
    for k, v in fields.items():
        out[k] = next(iter(v.values())) if v else None
    return out


def issue_of(item: dict) -> tuple[str, str]:
    text = (item.get("text") or "").strip()
    where = item.get("where") or "-"
    first = text.splitlines()[0][:50] if text else "(내용 없음)"
    title = f"[수정요청] {where} — {first}"
    body = (f"{text}\n\n---\n- 화면: {where}\n- 주소: {item.get('url') or '-'}\n"
            f"- 작성: {item.get('at') or '-'}\n- 화면 크기: {item.get('size') or '-'}\n- 사이트에서 바로 올림")
    return title, body


def firebase_token(info: dict) -> str:
    from google.oauth2 import service_account
    from google.auth.transport.requests import Request
    creds = service_account.Credentials.from_service_account_info(
        info, scopes=["https://www.googleapis.com/auth/datastore"])
    creds.refresh(Request())
    return creds.token


def reply_from(comments: list[dict]) -> str:
    """닫힌 이슈의 댓글 중 처리 답변을 고른다. Claude 가 단 댓글(꼬리말 있음)을 먼저, 없으면 봇이 아닌 마지막 댓글."""
    def body(c):
        b = re.split(r"\n-{3,}\s*\n_?Generated by", c.get("body") or "")[0]
        return b.strip()
    mine = [c for c in comments if "Generated by [Claude Code]" in (c.get("body") or "")]
    human = [c for c in comments if not (c.get("user") or {}).get("login", "").endswith("[bot]")
             and not (c.get("body") or "").startswith("✏️ 요청 내용이 수정됐어요")]
    pick = (mine or human or [None])[-1]
    return body(pick)[:2000] if pick else ""


def main() -> int:
    raw = os.environ.get("FIREBASE_SERVICE_ACCOUNT", "").strip()
    if not raw:
        print("[feedback] FIREBASE_SERVICE_ACCOUNT 가 없어 건너뜁니다")
        return 0
    info = json.loads(raw)
    project = info["project_id"]
    fb = firebase_token(info)
    gh = os.environ["GITHUB_TOKEN"]
    repo = os.environ["GITHUB_REPOSITORY"]
    api = f"https://api.github.com/repos/{repo}"

    # 모든 사용자의 feedback 을 한 번에 (필터 없는 컬렉션 그룹 조회라 색인이 필요 없다)
    rows = http("POST", f"{FIRESTORE}/projects/{project}/databases/(default)/documents:runQuery", fb,
                {"structuredQuery": {"from": [{"collectionId": "feedback", "allDescendants": True}]}})
    allowed = {u.strip() for u in os.environ.get("FEEDBACK_UIDS", "").split(",") if u.strip()} or OWNER_UIDS
    docs = [r["document"] for r in rows if r.get("document") and uid_of(r["document"]["name"]) in allowed]
    docs.sort(key=lambda d: d.get("createTime", ""))

    def patch(d: dict, values: dict) -> None:
        fields, mask = {}, []
        for k, v in values.items():
            mask.append(f"updateMask.fieldPaths={k}")
            if isinstance(v, bool):
                fields[k] = {"booleanValue": v}
            elif isinstance(v, int):
                fields[k] = {"integerValue": str(v)}
            else:
                fields[k] = {"stringValue": str(v)}
        http("PATCH", f"{FIRESTORE}/{d['name']}?{'&'.join(mask)}", fb, {"fields": fields})

    made = edited = closed = failed = 0
    for d in docs:
        f = plain(d.get("fields", {}))
        status, num = f.get("status"), int(f.get("issue") or 0)
        short = d["name"].rsplit("/", 1)[-1]
        try:
            if status == "new":
                title, body = issue_of(f)
                # 먼저 '옮기는 중'으로 바꿔 둔다. 도중에 끊겨도 다음 실행에서 같은 이슈를 또 만들지 않는다.
                patch(d, {"status": "issuing"})
                issue = http("POST", f"{api}/issues", gh, {"title": title, "body": body, "labels": ["수정요청"]})
                patch(d, {"status": "issued", "issue": issue["number"], "edited": False})
                print(f"[feedback] 이슈 #{issue['number']} 만듦: {title}")
                made += 1
                continue
            if not num:
                continue
            if f.get("edited") is True:
                text = (f.get("text") or "").strip()
                http("POST", f"{api}/issues/{num}/comments", gh,
                     {"body": f"✏️ 요청 내용이 수정됐어요 ({f.get('editedAt') or '-'})\n\n{text}"})
                if status == "done":
                    http("PATCH", f"{api}/issues/{num}", gh, {"state": "open"})
                patch(d, {"edited": False, "status": "issued", "reply": "" if status == "done" else (f.get("reply") or "")})
                print(f"[feedback] 이슈 #{num} 에 수정 내용 댓글")
                edited += 1
                continue
            if status == "issued":
                issue = http("GET", f"{api}/issues/{num}", gh)
                if issue.get("state") == "closed":
                    comments = http("GET", f"{api}/issues/{num}/comments?per_page=100", gh)
                    patch(d, {"status": "done", "reply": reply_from(comments),
                              "doneAt": (issue.get("closed_at") or "")[:16].replace("T", " ")})
                    print(f"[feedback] 이슈 #{num} 처리 완료 → 답변 옮김")
                    closed += 1
        except Exception as e:  # 하나가 실패해도 나머지는 계속
            failed += 1
            print(f"[feedback] 실패 ({short}): {e}")
    print(f"[feedback] 완료 — 새 이슈 {made}, 수정 반영 {edited}, 처리 완료 {closed}, 실패 {failed}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
