import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import feedback_to_issues as fb  # noqa: E402


class FeedbackTest(unittest.TestCase):
    def test_plain(self):
        self.assertEqual(fb.plain({"text": {"stringValue": "a"}, "issue": {"integerValue": "3"}}),
                         {"text": "a", "issue": "3"})

    def test_issue_of(self):
        title, body = fb.issue_of({"text": "글씨가 작아요\n키워 주세요", "where": "대시보드 · 사업공고",
                                   "url": "https://www.solworks.store/#notices", "at": "2026-10-15 09:00"})
        self.assertEqual(title, "[수정요청] 대시보드 · 사업공고 — 글씨가 작아요")
        self.assertIn("키워 주세요", body)
        self.assertIn("https://www.solworks.store/#notices", body)

    def test_uid_of(self):
        self.assertEqual(fb.uid_of("projects/p/databases/(default)/documents/users/U1/feedback/F1"), "U1")
        self.assertEqual(fb.uid_of("weird/path"), "")

    def test_reply_prefers_claude_comment(self):
        comments = [
            {"user": {"login": "github-actions[bot]"}, "body": "✏️ 요청 내용이 수정됐어요\n\n새 내용"},
            {"user": {"login": "esang159"}, "body": "카드 디자인을 바꿨어요.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"},
            {"user": {"login": "esang159"}, "body": "확인!"},
        ]
        self.assertEqual(fb.reply_from(comments), "카드 디자인을 바꿨어요.")
        self.assertEqual(fb.reply_from([{"user": {"login": "esang159"}, "body": "확인!"}]), "확인!")
        self.assertEqual(fb.reply_from([]), "")

    def test_no_secret_skips(self):
        import os
        old = os.environ.pop("FIREBASE_SERVICE_ACCOUNT", None)
        try:
            self.assertEqual(fb.main(), 0)
        finally:
            if old is not None:
                os.environ["FIREBASE_SERVICE_ACCOUNT"] = old


if __name__ == "__main__":
    unittest.main()
